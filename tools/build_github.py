"""Build github-data.js: the last year's contribution calendar and recent public repos.

    python tools/build_github.py            # uses your `gh` login

The calendar comes from GitHub's GraphQL API as you, so days with private-repo
work are counted the same way your profile shows them (counts only, no repo names).
"""
import json
import os
import subprocess
from datetime import datetime, timezone

USER = "GaneshKar1"
OUT = os.path.join(os.path.dirname(__file__), "..", "github-data.js")

QUERY = """
query($login:String!){ user(login:$login){
  contributionsCollection{
    restrictedContributionsCount
    contributionCalendar{ totalContributions weeks{ contributionDays{ date contributionCount } } }
  }
  repositories(first:30, privacy:PUBLIC, isFork:false, orderBy:{field:PUSHED_AT, direction:DESC}){
    nodes{ name description url pushedAt stargazerCount primaryLanguage{ name } }
  }
}}"""


def main():
    raw = subprocess.run(["gh", "api", "graphql", "-f", "query=" + QUERY, "-f", "login=" + USER],
                         check=True, capture_output=True, text=True).stdout
    u = json.loads(raw)["data"]["user"]
    cc = u["contributionsCollection"]
    days = [[d["date"], d["contributionCount"]]
            for w in cc["contributionCalendar"]["weeks"] for d in w["contributionDays"]]
    repos = [{"name": r["name"], "desc": r["description"], "url": r["url"], "pushed": r["pushedAt"][:10],
              "lang": (r["primaryLanguage"] or {}).get("name"), "stars": r["stargazerCount"]}
             for r in u["repositories"]["nodes"] if r["name"] != f"{USER}.github.io"]
    data = {"user": USER, "built": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
            "total": cc["contributionCalendar"]["totalContributions"],
            "private": cc["restrictedContributionsCount"], "days": days, "repos": repos}
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// GENERATED by tools/build_github.py. Do not edit by hand.\n")
        fh.write("window.GITHUB = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"{data['total']} contributions, {len(days)} days, {len(repos)} repos -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
