"""Build projects-data.js: the data behind the project-card charts on the home page.

    python tools/build_project_charts.py

Solar quantile analysis: numbers copied from the notebook's printed output
(GaneshKar1/Solar-Pannel-Quantile-Analysis, mde_quantile_analysis_FINAL.ipynb,
cells 23-27): the 21kWh+ storage-tier coefficient by quantile for MDE (with
95% CI = coef +/- 1.96 SE), QuantReg, and OLS. These are what Figure 3 plots.

Pairs trading: the WMT/TGT spread z-score, recomputed with the notebook's method
(GaneshKar1/Trading-Strat): 60-day rolling OLS hedge ratio, 30-day rolling
z-score on adjusted closes, 2020-01-01 to 2024-01-01, entry threshold 1.2. This
matches the notebook's chart (min -4.02 Nov 2023, max 3.58 Aug 2022). Only the signal is
stored, never strategy returns.
"""
import json
import os
from datetime import datetime, timezone

import yfinance as yf

OUT = os.path.join(os.path.dirname(__file__), "..", "projects-data.js")

SOLAR = {
    "quantiles": [0.10, 0.25, 0.50, 0.75, 0.90],
    "mde": [1.272, 1.039, 0.680, 0.399, 0.401],
    "mdeSE": [0.288, 0.195, 0.203, 0.309, 0.437],
    "quantreg": [1.754, 1.803, 1.211, 0.590, 0.380],
    "ols": 0.98,
    "label": "21 kWh+ battery premium, $/W vs. no storage",
}


def pairs():
    close = yf.download(["WMT", "TGT"], start="2020-01-01", end="2024-01-01", progress=False, auto_adjust=True)["Close"].dropna()
    x, y = close["TGT"], close["WMT"]
    # slope of a rolling OLS with intercept = rolling cov / rolling var
    beta = y.rolling(60).cov(x) / x.rolling(60).var()
    spread = y - beta * x
    z = ((spread - spread.rolling(30).mean()) / spread.rolling(30).std()).dropna()
    return {"start": z.index[0].strftime("%Y-%m-%d"), "end": z.index[-1].strftime("%Y-%m-%d"),
            "dates": [d.strftime("%Y-%m-%d") for d in z.index], "z": [round(float(v), 2) for v in z],
            "threshold": 1.2}


def main():
    data = {"built": datetime.now(timezone.utc).strftime("%Y-%m-%d"), "solar": SOLAR, "pairs": pairs()}
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// GENERATED by tools/build_project_charts.py. Do not edit by hand.\n")
        fh.write("window.PROJECT_CHARTS = " + json.dumps(data, separators=(",", ":")) + ";\n")
    p = data["pairs"]
    print(f"pairs: {len(p['z'])} days {p['start']}..{p['end']}, z range {min(p['z'])}..{max(p['z'])} -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
